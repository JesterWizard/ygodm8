#!/usr/bin/env python3
"""Build shop card-pack 8bpp tiles + pack metadata (names, prices, pools).

Each PNG is padded to 32x64 and nearest-color matched to the shop mini-card
palette so pack view does not replace gPaletteBuffer.

Pack names/prices/card pools come from tools/card_pack_manifest.json (editable).
"""

from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "src_custom" / "assets" / "card_packs"
OUT_DIR = ROOT / "build" / "card_packs"
GENERATED = ROOT / "src_custom" / "generated" / "card_pack_assets_generated.inc"
MANIFEST = ROOT / "tools" / "card_pack_manifest.json"
BASEROM = ROOT / "baserom.gba"
MINI_PAL_OFF = 0x09A781C
MINI_PAL_COLORS = 160

PACK_W = 32
PACK_H = 64
PACKS_IN_REVEAL = 5


def rgb555_to_rgb(c: int) -> tuple[int, int, int]:
    r = (c & 0x1F) << 3
    g = ((c >> 5) & 0x1F) << 3
    b = ((c >> 10) & 0x1F) << 3
    return (r, g, b)


def load_mini_palette() -> list[tuple[int, int, int]]:
    rom = BASEROM.read_bytes()
    return [
        rgb555_to_rgb(struct.unpack_from("<H", rom, MINI_PAL_OFF + i * 2)[0])
        for i in range(MINI_PAL_COLORS)
    ]


def nearest_index(rgb: tuple[int, int, int], pal: list[tuple[int, int, int]]) -> int:
    r, g, b = rgb
    best_i = 0
    best_d = 1 << 30
    for i, (pr, pg, pb) in enumerate(pal):
        d = (r - pr) * (r - pr) + (g - pg) * (g - pg) + (b - pb) * (b - pb)
        if d < best_d:
            best_d = d
            best_i = i
            if d == 0:
                break
    return best_i


def pad_to_32x64(im: Image.Image) -> Image.Image:
    """Center X; top-align Y so the pack's 2px container bars stay at the edges."""
    im = im.convert("RGBA")
    canvas = Image.new("RGBA", (PACK_W, PACK_H), (0, 0, 0, 0))
    x = (PACK_W - im.width) // 2
    canvas.paste(im, (x, 0), im)
    return canvas


def to_tiled_8bpp(indices: list[int], w: int, h: int) -> bytes:
    out = bytearray()
    for ty in range(h // 8):
        for tx in range(w // 8):
            for y in range(8):
                for x in range(8):
                    out.append(indices[(ty * 8 + y) * w + (tx * 8 + x)])
    return bytes(out)


def build_pack(png: Path, pal: list[tuple[int, int, int]]) -> Path:
    rgba = pad_to_32x64(Image.open(png))
    px = rgba.load()
    indices: list[int] = []
    for y in range(PACK_H):
        for x in range(PACK_W):
            r, g, b, a = px[x, y]
            indices.append(0 if a < 16 else nearest_index((r, g, b), pal))
    tiled = to_tiled_8bpp(indices, PACK_W, PACK_H)
    out_path = OUT_DIR / f"{png.stem}.8bpp"
    out_path.write_bytes(tiled)
    return out_path


def c_string(s: str) -> str:
    """Escape a C string literal; truncate to 28 chars for shop name row."""
    s = s[:28]
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_manifest(pngs: list[Path]) -> list[dict]:
    by_file = {p.name: p for p in pngs}
    if MANIFEST.is_file():
        data = json.loads(MANIFEST.read_text(encoding="utf-8"))
        entries = data.get("packs", [])
        out = []
        for i, ent in enumerate(entries):
            fname = ent.get("file") or f"card_pack_{i+1:02d}.png"
            if fname not in by_file:
                print(f"warning: manifest pack {fname} missing PNG, skip", file=sys.stderr)
                continue
            cards = [int(c) for c in ent.get("cards", [])]
            if len(cards) < PACKS_IN_REVEAL:
                # pad so a pack always has enough to draw 5
                base = i * 10 + 1
                while len(cards) < PACKS_IN_REVEAL:
                    cards.append(base + len(cards))
            out.append(
                {
                    "png": by_file[fname],
                    "name": ent.get("name") or f"Pack {i+1:02d}",
                    "price": int(ent.get("price", 100)),
                    "stock": min(99, max(0, int(ent.get("stock", 99)))),
                    "cards": cards,
                }
            )
        if out:
            return out

    # No usable manifest: one entry per PNG with boring defaults.
    return [
        {
            "png": png,
            "name": f"Pack {i+1:02d}",
            "price": 100,
            "stock": 99,
            "cards": list(range(i * 10 + 1, i * 10 + 11)),
        }
        for i, png in enumerate(pngs)
    ]


def main() -> int:
    pngs = sorted(SRC_DIR.glob("card_pack_*.png"))
    if not pngs:
        print(f"error: no card_pack_*.png in {SRC_DIR}", file=sys.stderr)
        return 1
    if not BASEROM.is_file():
        print(f"error: missing {BASEROM}", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    pal = load_mini_palette()
    packs = load_manifest(pngs)
    paths = [build_pack(p["png"], pal) for p in packs]
    n = len(packs)

    lines = [
        "/* Auto-generated by tools/build_card_packs.py — do not edit. */",
        "/* Packs remapped onto the shop mini-card palette (no palette swap). */",
        "/* Metadata from tools/card_pack_manifest.json. */",
        f"#define NUM_CARD_PACKS {n}",
        "#define CARD_PACK_HALF_BYTES 0x400",
        f"#define CARD_PACK_REVEAL_COUNT {PACKS_IN_REVEAL}",
        "",
    ]
    for i, path in enumerate(paths):
        rel = path.relative_to(ROOT).as_posix()
        lines.append(f"static const u8 sCardPackGfx{i:02d}[] APPEND_ASSET =")
        lines.append(f'    INCBIN_U8("{rel}");')
        lines.append("")
    lines.append("static const u8 *const sCardPackGfx[NUM_CARD_PACKS] APPEND_RODATA = {")
    for i in range(n):
        lines.append(f"    sCardPackGfx{i:02d},")
    lines.append("};")
    lines.append("")

    for i, p in enumerate(packs):
        lines.append(f"static const u8 sCardPackName{i:02d}[] APPEND_RODATA = {c_string(p['name'])};")
    lines.append("")
    lines.append("static const u8 *const sCardPackNames[NUM_CARD_PACKS] APPEND_RODATA = {")
    for i in range(n):
        lines.append(f"    sCardPackName{i:02d},")
    lines.append("};")
    lines.append("")

    lines.append("static const u16 sCardPackPrices[NUM_CARD_PACKS] APPEND_RODATA = {")
    lines.append("    " + ", ".join(str(p["price"]) for p in packs) + ",")
    lines.append("};")
    lines.append("")

    lines.append("static const u8 sCardPackStockDefault[NUM_CARD_PACKS] APPEND_RODATA = {")
    lines.append("    " + ", ".join(str(p["stock"]) for p in packs) + ",")
    lines.append("};")
    lines.append("")

    # Concatenated pools + offset table (length = off[i+1]-off[i]).
    pool: list[int] = []
    offs = [0]
    for p in packs:
        pool.extend(p["cards"])
        offs.append(len(pool))
    lines.append("static const u16 sCardPackPoolCards[] APPEND_RODATA = {")
    if pool:
        lines.append("    " + ", ".join(str(c) for c in pool) + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const u16 sCardPackPoolOff[NUM_CARD_PACKS + 1] APPEND_RODATA = {")
    lines.append("    " + ", ".join(str(o) for o in offs) + ",")
    lines.append("};")
    lines.append("")

    GENERATED.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {GENERATED.relative_to(ROOT)} ({n} packs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
