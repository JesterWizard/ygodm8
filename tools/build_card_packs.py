#!/usr/bin/env python3
"""Build shop card-pack 8bpp tiles remapped onto the mini-card palette.

Each PNG is padded to 32x64 and nearest-color matched to the shop mini-card
palette so pack view does not replace gPaletteBuffer.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "src_custom" / "assets" / "card_packs"
OUT_DIR = ROOT / "build" / "card_packs"
GENERATED = ROOT / "src_custom" / "generated" / "card_pack_assets_generated.inc"
BASEROM = ROOT / "baserom.gba"
MINI_PAL_OFF = 0x09A781C
MINI_PAL_COLORS = 160

PACK_W = 32
PACK_H = 64


def rgb555_to_rgb(c: int) -> tuple[int, int, int]:
    r = (c & 0x1F) << 3
    g = ((c >> 5) & 0x1F) << 3
    b = ((c >> 10) & 0x1F) << 3
    return (r, g, b)


def load_mini_palette() -> list[tuple[int, int, int]]:
    rom = BASEROM.read_bytes()
    return [
        rgb555_to_rgb(struct.unpack_from("<H", rom, MINI_PAL_OFF + i * 2)[0])
        for i in range(MINI_PAL_COLORS)
    ]


def nearest_index(rgb: tuple[int, int, int], pal: list[tuple[int, int, int]]) -> int:
    r, g, b = rgb
    best_i = 0
    best_d = 1 << 30
    for i, (pr, pg, pb) in enumerate(pal):
        d = (r - pr) * (r - pr) + (g - pg) * (g - pg) + (b - pb) * (b - pb)
        if d < best_d:
            best_d = d
            best_i = i
            if d == 0:
                break
    return best_i


def pad_to_32x64(im: Image.Image) -> Image.Image:
    """Center X; top-align Y so the pack's 2px container bars stay at the edges."""
    im = im.convert("RGBA")
    canvas = Image.new("RGBA", (PACK_W, PACK_H), (0, 0, 0, 0))
    x = (PACK_W - im.width) // 2
    canvas.paste(im, (x, 0), im)
    return canvas


def to_tiled_8bpp(indices: list[int], w: int, h: int) -> bytes:
    out = bytearray()
    for ty in range(h // 8):
        for tx in range(w // 8):
            for y in range(8):
                for x in range(8):
                    out.append(indices[(ty * 8 + y) * w + (tx * 8 + x)])
    return bytes(out)


def build_pack(png: Path, pal: list[tuple[int, int, int]]) -> Path:
    rgba = pad_to_32x64(Image.open(png))
    px = rgba.load()
    indices: list[int] = []
    for y in range(PACK_H):
        for x in range(PACK_W):
            r, g, b, a = px[x, y]
            indices.append(0 if a < 16 else nearest_index((r, g, b), pal))
    tiled = to_tiled_8bpp(indices, PACK_W, PACK_H)
    out_path = OUT_DIR / f"{png.stem}.8bpp"
    out_path.write_bytes(tiled)
    return out_path


def main() -> int:
    pngs = sorted(SRC_DIR.glob("card_pack_*.png"))
    if not pngs:
        print(f"error: no card_pack_*.png in {SRC_DIR}", file=sys.stderr)
        return 1
    if not BASEROM.is_file():
        print(f"error: missing {BASEROM}", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    pal = load_mini_palette()
    paths = [build_pack(png, pal) for png in pngs]

    lines = [
        "/* Auto-generated by tools/build_card_packs.py — do not edit. */",
        "/* Packs remapped onto the shop mini-card palette (no palette swap). */",
        f"#define NUM_CARD_PACKS {len(paths)}",
        "#define CARD_PACK_HALF_BYTES 0x400",
        "",
    ]
    for i, path in enumerate(paths):
        rel = path.relative_to(ROOT).as_posix()
        lines.append(f"static const u8 sCardPackGfx{i:02d}[] APPEND_ASSET =")
        lines.append(f'    INCBIN_U8("{rel}");')
        lines.append("")
    lines.append("static const u8 *const sCardPackGfx[NUM_CARD_PACKS] APPEND_RODATA = {")
    for i in range(len(paths)):
        lines.append(f"    sCardPackGfx{i:02d},")
    lines.append("};")
    lines.append("")

    GENERATED.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {GENERATED.relative_to(ROOT)} ({len(paths)} packs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
