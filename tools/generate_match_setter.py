#!/usr/bin/env python3
"""Generate debug Match Setter duelist table from vanilla_event_catalog.md."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "events/vanilla/vanilla_event_catalog.md"
PORTRAIT_TABLE = ROOT / "src_custom/debug/debug_menu_portrait_table.inc"
OVERWORLD_H = ROOT / "include/overworld.h"


def load_portrait_names() -> dict[int, str]:
    names: dict[int, str] = {}
    portrait_ids: dict[str, int] = {}
    enum = re.search(r"enum Portrait \{(.*?)\};", OVERWORLD_H.read_text(), re.S)
    if not enum:
        raise SystemExit("enum Portrait not found in include/overworld.h")
    value = 0
    for item in enum.group(1).split(","):
        item = item.strip()
        if not item:
            continue
        name, _, explicit = item.partition("=")
        name = name.strip()
        if explicit:
            value = int(explicit.strip(), 0)
        portrait_ids[name] = value
        value += 1

    for line in PORTRAIT_TABLE.read_text().splitlines():
        match = re.match(r'DEBUG_MENU_PORTRAIT_ENTRY\((PORTRAIT_[A-Z0-9_]+),\s*"([^"]+)"\)', line.strip())
        if not match:
            continue
        portrait_name = match.group(1)
        if portrait_name in portrait_ids:
            names[portrait_ids[portrait_name]] = match.group(2)
    return names


def extract_entries() -> list[dict[str, int | str]]:
    catalog = CATALOG.read_text()
    sections = re.split(r"^## ", catalog, flags=re.M)[1:]
    portrait_names = load_portrait_names()
    entries: dict[int, dict[str, int | str]] = {}

    for section in sections:
        sprite_lines = re.findall(
            r"- obj (\d+): sprite `(-?\d+)` at `(\d+),(\d+)` A `(0x[0-9A-Fa-f]+)` R `(0x[0-9A-Fa-f]+)`",
            section,
        )
        if not sprite_lines:
            continue

        script_info: dict[tuple[str, str], tuple[bool, bool, str]] = {}
        for match in re.finditer(r"- obj \d+ ([AR]): `(0x[0-9A-Fa-f]+)`\n((?:  - .*\n)*)", section):
            slot, addr, body = match.group(1), match.group(2).lower(), match.group(3)
            script_info[(slot, addr)] = ("portrait" in body, "duel" in body, body)

        for _, sprite, _, _, script_a, script_r in sprite_lines:
            script_a = script_a.lower()
            script_r = script_r.lower()
            if script_a == script_r:
                continue
            a_info = script_info.get(("A", script_a))
            r_info = script_info.get(("R", script_r))
            if not a_info or not r_info or not r_info[1]:
                continue
            if not (a_info[0] or r_info[0]):
                continue

            portrait = None
            for info in (a_info, r_info):
                portrait_match = re.search(r"portrait p(\d+)", info[2])
                if portrait_match:
                    portrait = int(portrait_match.group(1))
                    break
            if portrait is None or portrait in entries:
                continue

            entries[portrait] = {
                "portrait": portrait,
                "sprite": int(sprite),
                "title": portrait_names.get(portrait, f"Portrait {portrait}"),
                "script_a": script_a,
                "script_r": script_r,
            }

    return [entries[key] for key in sorted(entries)]


def render(entries: list[dict[str, int | str]]) -> str:
    lines = [
        "/* Generated by tools/generate_match_setter.py. Do not edit. */",
        "#define MATCH_SETTER_TABLE_ENTRY(spriteId, portraitId, title, scriptA, scriptR) \\",
        "  { spriteId, portraitId, title, (struct Script *)(scriptA), (struct Script *)(scriptR) },",
        "",
    ]
    for entry in entries:
        title = str(entry["title"]).replace("\\", "\\\\").replace('"', '\\"')
        lines.append(
            "MATCH_SETTER_TABLE_ENTRY("
            f"{entry['sprite']}, {entry['portrait']}, \"{title}\", "
            f"{entry['script_a']}, {entry['script_r']})"
        )
    lines.append("")
    lines.append(f"#define MATCH_SETTER_ENTRY_COUNT {len(entries)}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(extract_entries()))


if __name__ == "__main__":
    main()
