#!/usr/bin/env python3
"""Build opening screens and embed tile/palette blobs in generated INCBIN tables."""

from __future__ import annotations

import argparse
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OPENING_DIR = ROOT / "src_custom" / "assets" / "opening_screens"
OPENING_BUILD_DIR = ROOT / "build" / "opening_screens"
GENERATED_INC = ROOT / "src_custom" / "generated" / "opening_screen_assets_generated.inc"
REQUIRED_STEMS = ("opening_screen_1", "opening_screen_2", "opening_screen_3")
OPENING_SCREEN_COUNT = 3
BYTES_PER_LINE = 12


def stem_to_symbol(stem: str) -> str:
    if stem.startswith("opening_screen_"):
        return "sOpeningScreen" + stem.removeprefix("opening_screen_")
    parts = [part for part in re.split(r"[^A-Za-z0-9]+", stem) if part]
    if not parts:
        raise ValueError(f"invalid opening screen stem {stem!r}")
    return "sOpening" + "".join(part[:1].upper() + part[1:] for part in parts)


def format_byte_lines(data: bytes, indent: str = "    ") -> list[str]:
    lines: list[str] = []
    chunk: list[str] = []
    for byte in data:
        chunk.append(f"0x{byte:02X}")
        if len(chunk) == BYTES_PER_LINE:
            lines.append(f"{indent}{', '.join(chunk)},")
            chunk = []
    if chunk:
        lines.append(f"{indent}{', '.join(chunk)},")
    return lines


def format_palette_lines(data: bytes, indent: str = "    ") -> list[str]:
    if len(data) % 2 != 0:
        raise ValueError("palette blob must contain an even number of bytes")
    words = [struct.unpack_from("<H", data, offset)[0] for offset in range(0, len(data), 2)]
    lines: list[str] = []
    chunk: list[str] = []
    for word in words:
        chunk.append(f"0x{word:04X}")
        if len(chunk) == BYTES_PER_LINE:
            lines.append(f"{indent}{', '.join(chunk)},")
            chunk = []
    if chunk:
        lines.append(f"{indent}{', '.join(chunk)},")
    return lines


def build_assets(stems: list[str]) -> dict[str, tuple[Path, Path]]:
    sys.path.insert(0, str(ROOT / "tools"))
    from build_opening_screen import build_screen  # noqa: E402

    built: dict[str, tuple[Path, Path]] = {}
    for stem in stems:
        lz_path, pal_path = build_screen(OPENING_DIR / f"{stem}.png")
        built[stem] = (lz_path, pal_path)
    return built


def render_assets_inc(stems: list[str], built: dict[str, tuple[Path, Path]]) -> str:
    lines = [
        "/* Generated by tools/generate_opening_screen_assets.py. Do not edit. */",
        "",
    ]

    for stem in stems:
        symbol = stem_to_symbol(stem)
        lz_path, pal_path = built[stem]
        tile_data = lz_path.read_bytes()
        palette_data = pal_path.read_bytes()

        lines.append(f"const u8 {symbol}Tiles[] APPEND_ASSET = {{")
        lines.extend(format_byte_lines(tile_data))
        lines.append("};")
        lines.append(f"const u16 {symbol}Palette[] APPEND_ASSET = {{")
        lines.extend(format_palette_lines(palette_data))
        lines.append("};")
        lines.append("")

    lines.append("struct OpeningScreenAsset {")
    lines.append("  const u8 *tiles;")
    lines.append("  const u16 *palette;")
    lines.append("};")
    lines.append("")
    lines.append("const struct OpeningScreenAsset sOpeningScreenAssets[OPENING_SCREEN_COUNT] APPEND_RODATA = {")
    for stem in stems:
        symbol = stem_to_symbol(stem)
        lines.append("  {")
        lines.append(f"    .tiles = {symbol}Tiles,")
        lines.append(f"    .palette = {symbol}Palette,")
        lines.append("  },")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def generate() -> str:
    for stem in REQUIRED_STEMS:
        png_path = OPENING_DIR / f"{stem}.png"
        if not png_path.is_file():
            raise SystemExit(f"missing required opening screen PNG: {png_path}")
    built = build_assets(list(REQUIRED_STEMS))
    return render_assets_inc(list(REQUIRED_STEMS), built)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--inc-out",
        type=Path,
        default=GENERATED_INC,
        help=f"Generated asset include (default: {GENERATED_INC.relative_to(ROOT)})",
    )
    args = parser.parse_args()

    inc_text = generate()
    args.inc_out.parent.mkdir(parents=True, exist_ok=True)
    args.inc_out.write_text(inc_text)
    print(f"generate_opening_screen_assets: ok ({OPENING_SCREEN_COUNT} screen(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
