#!/usr/bin/env python3
"""Phase 4b: JSON effect-script manifest → C table include.

Source: tools/effect_scripts_manifest.json
Output: src_custom/generated/effect_scripts_table.inc

Hand-authored canActivate / afterSteps symbols stay in C; the generator only
emits step arrays + the EffectScript table rows.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "tools" / "effect_scripts_manifest.json"
OUT = ROOT / "src_custom" / "generated" / "effect_scripts_table.inc"
OUT_REGISTRY = ROOT / "src_custom" / "generated" / "effect_registry.inc"

OP_ENUM = {
    "END": "EFFECT_SCRIPT_END",
    "SHOW_TEXT": "EFFECT_SCRIPT_SHOW_TEXT",
    "DRAW": "EFFECT_SCRIPT_DRAW",
    "CHANGE_LP": "EFFECT_SCRIPT_CHANGE_LP",
    "DESTROY_ALL_MONSTERS_ROW": "EFFECT_SCRIPT_DESTROY_ALL_MONSTERS_ROW",
    "DESTROY_ACTIVATING_SPELL": "EFFECT_SCRIPT_DESTROY_ACTIVATING_SPELL",
    "OPT_REQUIRE": "EFFECT_SCRIPT_OPT_REQUIRE",
    "OPT_MARK": "EFFECT_SCRIPT_OPT_MARK",
    "REQUIRE_COND": "EFFECT_SCRIPT_REQUIRE_COND",
    "DESTROY_FIRST_BY_COND": "EFFECT_SCRIPT_DESTROY_FIRST_BY_COND",
    "BURN_THROUGH_TRAPS": "EFFECT_SCRIPT_BURN_THROUGH_TRAPS",
    "HEAL_THROUGH_TRAPS": "EFFECT_SCRIPT_HEAL_THROUGH_TRAPS",
    "DESTROY_INACTIVE_MONSTERS_THROUGH_TRAPS": "EFFECT_SCRIPT_DESTROY_INACTIVE_MONSTERS_THROUGH_TRAPS",
    "SEARCH_DECK_BY_ID": "EFFECT_SCRIPT_SEARCH_DECK_BY_ID",
    "DESTROY_ALL_MONSTERS_OF_TYPE": "EFFECT_SCRIPT_DESTROY_ALL_MONSTERS_OF_TYPE",
    "DESTROY_ALL_IN_TURN_ROW": "EFFECT_SCRIPT_DESTROY_ALL_IN_TURN_ROW",
    "STEAL_LP_THROUGH_TRAPS": "EFFECT_SCRIPT_STEAL_LP_THROUGH_TRAPS",
    "UPSTART_THROUGH_TRAPS": "EFFECT_SCRIPT_UPSTART_THROUGH_TRAPS",
    "BOTH_PLAYERS_HEAL_THROUGH_TRAPS": "EFFECT_SCRIPT_BOTH_PLAYERS_HEAL_THROUGH_TRAPS",
    "DESTROY_ALL_HAND_EXCEPT_GODS": "EFFECT_SCRIPT_DESTROY_ALL_HAND_EXCEPT_GODS",
    "DESTROY_MONSTERS_FINAL_ATK_GTE": "EFFECT_SCRIPT_DESTROY_MONSTERS_FINAL_ATK_GTE",
    "DESTROY_HIGHEST_ATK_IN_ROW": "EFFECT_SCRIPT_DESTROY_HIGHEST_ATK_IN_ROW",
    "BURN_PER_OPP_HAND_CARD": "EFFECT_SCRIPT_BURN_PER_OPP_HAND_CARD",
    "FACE_UP_MONSTERS_IN_ROW": "EFFECT_SCRIPT_FACE_UP_MONSTERS_IN_ROW",
    "FACE_UP_HAND": "EFFECT_SCRIPT_FACE_UP_HAND",
    "DECREMENT_PERM_STAGE_ROW": "EFFECT_SCRIPT_DECREMENT_PERM_STAGE_ROW",
    "RESET_NEGATIVE_PERM_STAGE_ROW": "EFFECT_SCRIPT_RESET_NEGATIVE_PERM_STAGE_ROW",
    "APPLY_STOP_DEFENSE": "EFFECT_SCRIPT_APPLY_STOP_DEFENSE",
    "ACTIVATE_CONTINUOUS_ZONE": "EFFECT_SCRIPT_ACTIVATE_CONTINUOUS_ZONE",
    "MILL_DECK_DIFFERENCE_TO_OPP": "EFFECT_SCRIPT_MILL_DECK_DIFFERENCE_TO_OPP",
    "DESTROY_ACTIVE_MONSTERS_BURN_PER_THROUGH_TRAPS": "EFFECT_SCRIPT_DESTROY_ACTIVE_MONSTERS_BURN_PER_THROUGH_TRAPS",
}

KIND_ENUM = {
    "SPELL": "EFFECT_KIND_SPELL",
    "TRAP": "EFFECT_KIND_TRAP",
    "ACTIVATED": "EFFECT_KIND_ACTIVATED",
    "PERMANENT": "EFFECT_KIND_PERMANENT",
    "TURN": "EFFECT_KIND_TURN",
}

META_ENUM = {
    "NONE": "EFFECT_META_NONE",
    "DRAW": "EFFECT_META_DRAW",
    "DESTROY": "EFFECT_META_DESTROY",
    "BURN": "EFFECT_META_BURN",
    "SEARCH": "EFFECT_META_SEARCH",
    "HEAL": "EFFECT_META_HEAL",
}


def bool_c(v: bool | int | None) -> str:
    if v is True or v == 1:
        return "TRUE"
    return "FALSE"


def step_args(step: dict) -> tuple[str, str, str, str]:
    a0 = step.get("a0", 0)
    a1 = step.get("a1", 0)
    a2 = step.get("a2", 0)
    s0 = step.get("s0", 0)
    a0_s = str(a0) if not isinstance(a0, bool) else bool_c(a0)
    a1_s = str(a1) if not isinstance(a1, bool) else bool_c(a1)
    a2_s = bool_c(a2) if isinstance(a2, bool) else str(a2)
    return a0_s, a1_s, a2_s, str(s0)


def emit_steps(card_id: str, steps: list[dict]) -> str:
    lines = [
        f"static const struct EffectScriptStep s{card_id}Steps[] "
        f"__attribute__((section(\".text\"))) = {{"
    ]
    for step in steps:
        op = step["op"]
        if op not in OP_ENUM:
            raise SystemExit(f"unknown op {op!r} for {card_id}")
        a0, a1, a2, s0 = step_args(step)
        lines.append(f"  {{ {OP_ENUM[op]}, {a0}, {a1}, {a2}, {s0} }},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def generate(manifest_path: Path, out_path: Path, registry_path: Path) -> None:
    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    scripts = data.get("scripts", [])
    if not scripts:
        raise SystemExit("manifest has no scripts")

    decls: list[str] = []
    seen_cb: set[str] = set()
    for s in scripts:
        ca = s.get("canActivate")
        if ca and ca not in seen_cb:
            decls.append(f"u8 {ca}(void);")
            seen_cb.add(ca)
        af = s.get("afterSteps")
        if af and af not in seen_cb:
            decls.append(f"void {af}(void);")
            seen_cb.add(af)

    parts: list[str] = [
        "/* AUTO-GENERATED by tools/generate_effect_scripts.py — do not edit. */",
        f"/* Source: {manifest_path.relative_to(ROOT)} */",
        "",
    ]
    if decls:
        parts.extend(decls)
        parts.append("")

    for s in scripts:
        parts.append(emit_steps(s["cardId"], s["steps"]))

    parts.append(
        "static const struct EffectScript sEffectScripts[] "
        "__attribute__((section(\".text\"))) = {"
    )
    for s in scripts:
        card = s["cardId"]
        kind = KIND_ENUM[s["kind"]]
        meta = META_ENUM[s.get("meta", "NONE")]
        can = s.get("canActivate") or "NULL"
        after = s.get("afterSteps") or "NULL"
        parts.append("  {")
        parts.append(f"    {card},")
        parts.append(f"    {kind},")
        parts.append(f"    ARRAY_COUNT(s{card}Steps),")
        parts.append(f"    s{card}Steps,")
        parts.append(f"    {{ {meta}, 0, 0 }},")
        parts.append(f"    {can},")
        parts.append(f"    {after},")
        parts.append("  },")
    parts.append("};")
    parts.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out_path.relative_to(ROOT)} ({len(scripts)} scripts)")

    # YGOPRO-shaped Effect registry: one ACTIVATE Effect per script.
    reg: list[str] = [
        "/* AUTO-GENERATED by tools/generate_effect_scripts.py — do not edit. */",
        f"/* Source: {manifest_path.relative_to(ROOT)} */",
        "/* ACTIVATE Effects; operation = EffectOp_RunScript (step tables). */",
        "",
        "static const struct Effect sEffectsFromScripts[] "
        "__attribute__((section(\".text\"))) = {",
    ]
    for s in scripts:
        card = s["cardId"]
        kind = KIND_ENUM[s["kind"]]
        meta = META_ENUM[s.get("meta", "NONE")]
        reg.append("  {")
        reg.append(f"    {card},")
        reg.append(f"    {kind},")
        reg.append("    EFFECT_TYPE_ACTIVATE,")
        reg.append("    EFFECT_CODE_ACTIVATE,")
        reg.append(f"    {meta},")
        reg.append("    EFFECT_FLAG_NONE,")
        reg.append("    EffectCond_ScriptGate,")
        reg.append("    NULL,")
        reg.append("    NULL,")
        reg.append("    EffectOp_RunScript,")
        reg.append("  },")
    reg.append("};")
    reg.append("")
    registry_path.parent.mkdir(parents=True, exist_ok=True)
    registry_path.write_text("\n".join(reg), encoding="utf-8")
    print(f"wrote {registry_path.relative_to(ROOT)} ({len(scripts)} effects)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--registry-out", type=Path, default=OUT_REGISTRY)
    args = ap.parse_args()
    generate(args.manifest, args.out, args.registry_out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
