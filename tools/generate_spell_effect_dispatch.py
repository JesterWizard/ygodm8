#!/usr/bin/env python3
"""Generate spell effect dispatch tables and activation gates from hook sources."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPELL_EFFECTS_DIR = ROOT / "src_custom" / "spell_effects"
TRAP_EFFECTS_DIR = ROOT / "src_custom" / "trap_effects"
GENERATED_DIR = ROOT / "src_custom" / "generated"
DECLS_INC = GENERATED_DIR / "spell_effect_dispatch_decls.inc"
CASES_INC = GENERATED_DIR / "spell_effect_dispatch_cases.inc"
GATES_INC = GENERATED_DIR / "spell_activation_gates_generated.inc"
GATES_C = GENERATED_DIR / "spell_activation_gates.c"
GATES_H = ROOT / "include" / "spell_activation_gates.h"

EFFECT_FN_RE = re.compile(
    r"^(?:APPEND_TEXT )?void (Effect\w+?)(?:__Replacement)?\(void\)\s*\{",
    re.MULTILINE,
)
GATE_FN_RE = re.compile(r"^u8 (CanActivate\w+)\(void\)", re.MULTILINE)

# ponytail: only GUARDIAN_TREASURE omits forbidden SFX today; extend when another card needs it
GATES_WITHOUT_FORBIDDEN_SFX = frozenset({"GUARDIAN_TREASURE"})

# Cards with CanActivate(void) but a custom pre-activation path in code_8043EF4_hooks.c
SKIP_ACTIVATION_GATE_STEMS = frozenset({
    "nightmare_wheel",
    "tribute_doll",
})

# Helper modules — no card dispatch entry
SKIP_STEMS = frozenset({"dynamic_equip", "evolution_end_burst"})

# Trap hook files also reached from ActivateSpellEffect__Body (not all trap_effects/*.c)
TRAP_SPELL_DISPATCH_STEMS = frozenset({
    "bottomless_shifting_sand",
    "coffin_seller",
    "dust_tornado",
    "level_limit_area_a",
    "ring_of_destruction",
    "skull_invitation",
})

# LynJump replacements on vanilla Effect* — routed via spellEffect enum, not card-id switch
SKIP_REPLACEMENT_STEMS = frozenset({
    "sparks",
    "hinotama",
    "ookazi",
    "tremendous_fire",
    "final_flame",
    "brain_control",
    "change_of_heart",
})


def stem_to_card_const(stem: str) -> str:
    return stem.upper()


def scan_effect_entry(path: Path) -> tuple[str, str] | None:
    stem = path.stem
    if stem in SKIP_STEMS:
        return None
    if stem in SKIP_REPLACEMENT_STEMS:
        return None

    content = path.read_text()
    match = EFFECT_FN_RE.search(content)
    if not match:
        return None
    if match.group(0).find("__Replacement") >= 0:
        return None
    card_const = stem_to_card_const(stem)
    return card_const, match.group(1)


def scan_activation_gate(path: Path) -> tuple[str, str] | None:
    if path.stem in SKIP_ACTIVATION_GATE_STEMS:
        return None
    content = path.read_text()
    match = GATE_FN_RE.search(content)
    if not match:
        return None
    card_const = stem_to_card_const(path.stem)
    return card_const, match.group(1)


def iter_dispatch_sources() -> list[Path]:
    paths = sorted(SPELL_EFFECTS_DIR.glob("*.c"))
    for stem in sorted(TRAP_SPELL_DISPATCH_STEMS):
        path = TRAP_EFFECTS_DIR / f"{stem}.c"
        if path.is_file():
            paths.append(path)
    return paths


def collect_dispatches() -> list[tuple[str, str]]:
    entries: dict[str, str] = {}
    for path in iter_dispatch_sources():
        item = scan_effect_entry(path)
        if item is None:
            continue
        card_const, effect_fn = item
        if card_const in entries and entries[card_const] != effect_fn:
            raise SystemExit(
                f"Duplicate dispatch for {card_const}: {entries[card_const]} vs {effect_fn}"
            )
        entries[card_const] = effect_fn

    return sorted(entries.items())


def collect_gates() -> list[tuple[str, str, bool]]:
    gates: dict[str, tuple[str, bool]] = {}
    for path in sorted(SPELL_EFFECTS_DIR.glob("*.c")):
        item = scan_activation_gate(path)
        if item is None:
            continue
        card_const, gate_fn = item
        play_sfx = card_const not in GATES_WITHOUT_FORBIDDEN_SFX
        gates[card_const] = (gate_fn, play_sfx)

    return sorted((card, fn, sfx) for card, (fn, sfx) in gates.items())


def render_decls(dispatches: list[tuple[str, str]]) -> str:
    lines = [
        "/* Auto-generated by tools/generate_spell_effect_dispatch.py — do not edit. */",
    ]
    for _card_const, effect_fn in dispatches:
        lines.append(f"extern void {effect_fn}(void);")
    lines.append("")
    return "\n".join(lines)


def render_cases(dispatches: list[tuple[str, str]]) -> str:
    lines = [
        "/* Auto-generated by tools/generate_spell_effect_dispatch.py — do not edit. */",
    ]
    for card_const, effect_fn in dispatches:
        lines.append(f"    case {card_const}:")
        lines.append(f"      {effect_fn}();")
        lines.append("      return;")
    return "\n".join(lines)


def render_gates_header() -> str:
    return """\
#ifndef GUARD_SPELL_ACTIVATION_GATES_H
#define GUARD_SPELL_ACTIVATION_GATES_H

#include "global.h"

u8 TryRejectSpellActivationGate(u16 cardId);

#endif // GUARD_SPELL_ACTIVATION_GATES_H
"""


def render_gates_c(gates: list[tuple[str, str, bool]]) -> str:
    lines = [
        "/* Auto-generated by tools/generate_spell_effect_dispatch.py — do not edit. */",
        "",
        '#include "global.h"',
        '#include "common-chax.h"',
        '#include "constants/card_ids.h"',
        '#include "spell_activation_gates.h"',
        "",
        "void DisplayCardInfoBar(void);",
        "void sub_8041E70(u8, u8);",
        "",
        "typedef u8 (*SpellActivationGateFn)(void);",
        "",
        "struct SpellActivationGateEntry {",
        "  u16 cardId;",
        "  SpellActivationGateFn canActivate;",
        "  u8 playForbiddenSfx;",
        "};",
        "",
    ]
    for _card_const, gate_fn, _sfx in gates:
        lines.append(f"extern u8 {gate_fn}(void);")
    lines.append("")
    lines.append("static const struct SpellActivationGateEntry sSpellActivationGates[] __attribute__((section(\".text\"))) = {")
    for card_const, gate_fn, play_sfx in gates:
        sfx = "TRUE" if play_sfx else "FALSE"
        lines.append(f"  {{ {card_const}, {gate_fn}, {sfx} }},")
    lines.append("};")
    lines.append("")
    lines.append("u8 TryRejectSpellActivationGate(u16 cardId)")
    lines.append("{")
    lines.append("  u8 i;")
    lines.append("")
    lines.append("  for (i = 0; i < ARRAY_COUNT(sSpellActivationGates); i++) {")
    lines.append("    if (sSpellActivationGates[i].cardId != cardId)")
    lines.append("      continue;")
    lines.append("    if (sSpellActivationGates[i].canActivate())")
    lines.append("      return FALSE;")
    lines.append("    if (sSpellActivationGates[i].playForbiddenSfx)")
    lines.append("      PlayMusic(SFX_FORBIDDEN);")
    lines.append("    gDuelCursor.state = 0;")
    lines.append("    DisplayCardInfoBar();")
    lines.append("    sub_8041E70(gDuelCursor.destY, gDuelCursor.currentY);")
    lines.append("    return TRUE;")
    lines.append("  }")
    lines.append("  return FALSE;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_outputs() -> None:
    dispatches = collect_dispatches()
    gates = collect_gates()

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    DECLS_INC.write_text(render_decls(dispatches))
    CASES_INC.write_text(render_cases(dispatches))
    GATES_H.write_text(render_gates_header())
    GATES_C.write_text(render_gates_c(gates))

    print(
        f"Generated {len(dispatches)} spell dispatches, {len(gates)} activation gates",
        file=sys.stderr,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stamp", metavar="PATH", help="Write stamp file after generation")
    args = parser.parse_args()

    write_outputs()

    if args.stamp:
        stamp_path = Path(args.stamp)
        stamp_path.parent.mkdir(parents=True, exist_ok=True)
        stamp_path.write_text("ok\n")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
