#!/usr/bin/env python3
"""Build title screen assets and embed tile/palette blobs in generated INCBIN tables."""

from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TITLE_DIR = ROOT / "src_custom" / "assets" / "title_screens"
GENERATED_INC = ROOT / "src_custom" / "generated" / "title_screen_assets_generated.inc"
RESERVED_INC = ROOT / "src_custom" / "generated" / "title_screen_palette_reservations_generated.inc"
REQUIRED_STEM = "title_screen"
BYTES_PER_LINE = 12


def format_byte_lines(data: bytes, indent: str = "    ") -> list[str]:
    lines: list[str] = []
    chunk: list[str] = []
    for byte in data:
        chunk.append(f"0x{byte:02X}")
        if len(chunk) == BYTES_PER_LINE:
            lines.append(f"{indent}{', '.join(chunk)},")
            chunk = []
    if chunk:
        lines.append(f"{indent}{', '.join(chunk)},")
    return lines


def format_palette_lines(data: bytes, indent: str = "    ") -> list[str]:
    if len(data) % 2 != 0:
        raise ValueError("palette blob must contain an even number of bytes")
    words = [struct.unpack_from("<H", data, offset)[0] for offset in range(0, len(data), 2)]
    lines: list[str] = []
    chunk: list[str] = []
    for word in words:
        chunk.append(f"0x{word:04X}")
        if len(chunk) == BYTES_PER_LINE:
            lines.append(f"{indent}{', '.join(chunk)},")
            chunk = []
    if chunk:
        lines.append(f"{indent}{', '.join(chunk)},")
    return lines


def validate_palette_blob(palette_data: bytes, png_path: Path) -> None:
    if len(palette_data) != 512:
        raise SystemExit(f"{png_path.name}: expected 512-byte palette blob, got {len(palette_data)}")

    sys.path.insert(0, str(ROOT / "tools"))
    from validate_title_screen import validate_title_png  # noqa: E402

    errors = validate_title_png(png_path)
    if errors:
        raise SystemExit("\n".join(errors))

    from PIL import Image

    image = Image.open(png_path)
    used = set(image.get_flattened_data())
    missing = [
        index
        for index in sorted(used)
        if struct.unpack_from("<H", palette_data, index * 2)[0] == 0
    ]
    if missing:
        preview = ", ".join(str(index) for index in missing[:8])
        suffix = "..." if len(missing) > 8 else ""
        raise SystemExit(
            f"{png_path.name}: palette blob has zeroed entries for used indices "
            f"({preview}{suffix}); regenerate from the indexed PNG"
        )


def build_assets() -> tuple[bytes, bytes]:
    sys.path.insert(0, str(ROOT / "tools"))
    from build_title_screen import build_screen  # noqa: E402

    png_path = TITLE_DIR / f"{REQUIRED_STEM}.png"
    if not png_path.is_file():
        raise SystemExit(f"missing required title screen PNG: {png_path}")
    lz_path, pal_path = build_screen(png_path)
    palette_data = pal_path.read_bytes()
    validate_palette_blob(palette_data, png_path)
    return lz_path.read_bytes(), palette_data


def generate_reserved_indices() -> None:
    rom_candidates = (ROOT / "ygodm8.gba", ROOT / "baserom.gba")
    rom_path = next((path for path in rom_candidates if path.is_file()), None)
    if rom_path is None:
        if RESERVED_INC.is_file():
            print(
                "generate_title_screen_assets: skipping palette reservation scan "
                f"(no ROM found; keeping {RESERVED_INC.relative_to(ROOT)})"
            )
            return
        raise SystemExit(
            "missing ROM for palette reservation scan: need ygodm8.gba or baserom.gba"
        )

    cmd = [
        sys.executable,
        str(ROOT / "tools/extract_title_screen_palette_reservations.py"),
        "--rom",
        str(rom_path),
        "--out",
        str(RESERVED_INC),
    ]
    subprocess.run(cmd, check=True, cwd=ROOT)


def render_assets_inc(tile_data: bytes, palette_data: bytes) -> str:
    lines = [
        "/* Generated by tools/generate_title_screen_assets.py. Do not edit. */",
        "",
        "const u8 sTitleScreenTiles[] APPEND_ASSET = {",
        *format_byte_lines(tile_data),
        "};",
        "const u16 sTitleScreenPalette[] APPEND_ASSET = {",
        *format_palette_lines(palette_data),
        "};",
        "",
    ]
    return "\n".join(lines)


def generate() -> str:
    tile_data, palette_data = build_assets()
    try:
        generate_reserved_indices()
    except subprocess.CalledProcessError as exc:
        raise SystemExit(exc) from exc
    return render_assets_inc(tile_data, palette_data)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--inc-out",
        type=Path,
        default=GENERATED_INC,
        help=f"Generated asset include (default: {GENERATED_INC.relative_to(ROOT)})",
    )
    args = parser.parse_args()

    inc_text = generate()
    args.inc_out.parent.mkdir(parents=True, exist_ok=True)
    args.inc_out.write_text(inc_text)
    print("generate_title_screen_assets: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
