#!/usr/bin/env python3
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AI_C = ROOT / "src/duel/ai.c"
OUT = ROOT / "src_custom/generated/ai_action_table_generated.inc"
EXPECTED_COUNT = 0x3B2

TURN_ROW = {
    "INACTIVE_DUELIST_BACKROW": 0,
    "INACTIVE_DUELIST_MONSTER_ROW": 1,
    "ACTIVE_DUELIST_MONSTER_ROW": 2,
    "ACTIVE_DUELIST_BACKROW": 3,
    "ACTIVE_DUELIST_HAND": 4,
}


def load_ai_action_enum():
    text = AI_C.read_text()
    match = re.search(r"\benum\s+AI_Action\s*\{(.*?)\};", text, re.DOTALL)
    if not match:
        raise SystemExit("enum AI_Action not found in src/duel/ai.c")
    constants = {}
    value = 0
    for raw_item in match.group(1).split(","):
        item = re.sub(r"//.*", "", raw_item).strip()
        if not item:
            continue
        name, _, explicit = item.partition("=")
        name = name.strip()
        if explicit:
            value = int(explicit.strip().split()[0], 0)
        constants[name] = value
        if not explicit:
            value += 1
    return constants


def parse_zone_position(expr):
    expr = expr.strip()
    match = re.match(r"ZONE_POSITION\s*\(\s*(\w+)\s*,\s*(\d+)\s*\)", expr)
    if not match:
        raise SystemExit(f"unsupported zone expression: {expr!r}")
    row_name, col = match.group(1), int(match.group(2))
    if row_name not in TURN_ROW:
        raise SystemExit(f"unknown turn row {row_name!r}")
    return (TURN_ROW[row_name] << 4) | col


def parse_gaed58():
    text = AI_C.read_text()
    match = re.search(
        r"static const struct AI_Command gAED58\[\]\s*=\s*\{(.*?)\n\};",
        text,
        re.DOTALL,
    )
    if not match:
        raise SystemExit("gAED58 table not found in src/duel/ai.c")

    action_enum = load_ai_action_enum()
    entries = []
    for block in re.finditer(r"\{([^{}]*)\}", match.group(1)):
        body = block.group(1)
        action_match = re.search(r"\.action\s*=\s*(\w+)", body)
        if not action_match:
            raise SystemExit(f"missing .action in block: {body!r}")
        action_name = action_match.group(1)
        if action_name not in action_enum:
            raise SystemExit(f"unknown action {action_name!r}")
        zones = [0, 0, 0, 0, 0, 0]
        for idx in range(1, 7):
            zone_match = re.search(
                rf"\.zone{idx}Position\s*=\s*(ZONE_POSITION\s*\([^)]+\))",
                body,
            )
            if zone_match:
                zones[idx - 1] = parse_zone_position(zone_match.group(1))
        entries.append((action_enum[action_name], zones))

    if len(entries) != EXPECTED_COUNT:
        raise SystemExit(
            f"gAED58 entry count {len(entries)} != expected {EXPECTED_COUNT}"
        )
    return entries


def render(entries):
    lines = [
        "/* Auto-generated by tools/generate_ai_action_table.py; do not edit. */",
        f"#define AI_ACTION_TABLE_COUNT {len(entries)}",
        "",
        "static const struct AiActionTemplate sAiActionTable[] APPEND_RODATA = {",
    ]
    for action, zones in entries:
        zone_str = ", ".join(f"0x{z:02X}" for z in zones)
        lines.append(f"  {{ {action}, {{ {zone_str} }} }},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    entries = parse_gaed58()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(entries) + "\n", encoding="utf-8")
    print(f"wrote {args.out} ({len(entries)} actions)")


if __name__ == "__main__":
    main()
